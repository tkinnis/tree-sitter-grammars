/// Publishes a packed release to GitHub with the GitHub CLI, once: a release
/// that already exists is never changed.
library;

import 'package:path/path.dart' as p;

import 'build_platform.dart';
import 'github.dart';

export 'github.dart' show PublishException, ProcessRunner, releaseRepository;

/// Creates the GitHub release [tag] of [releaseRepository] with [assets],
/// whose sha256 digests are the values of the map, and the notes in
/// [notesFile].
///
/// Refuses when the release exists already, so an asset is never replaced.
/// Before creating it, [tag] on GitHub must be an annotated tag whose
/// object is [tagObject], the local tag the build checked, and which names
/// [commit], the commit that was built: a tag re-created locally after the
/// push, or moved on GitHub, is refused. After the upload, the tag must
/// still name [commit] and every asset's digest as GitHub reports it must
/// be the local one. Throws a [PublishException] naming the first step
/// that fails.
Future<void> publishRelease({
  required String tag,
  required String tagObject,
  required String commit,
  required Map<String, String> assets,
  required String notesFile,
  ProcessRunner run = runProcess,
}) async {
  final gh = githubCli(run);
  Future<void> requireTag(String when) => requirePushedTag(
    gh,
    tag: tag,
    tagObject: tagObject,
    commit: commit,
    when: when,
  );

  final existing = await releasesOfTag(gh, tag);
  if (existing.isNotEmpty) {
    throw PublishException(
      'release $tag exists on $releaseRepository'
      '${existing.any((release) => release.draft) ? ' as a draft' : ''}; '
      'a release is created once and never replaced',
    );
  }
  await requireTag('before publishing');
  final creation = await gh([
    'release',
    'create',
    tag,
    '--repo',
    releaseRepository,
    '--draft',
    '--target',
    commit,
    '--verify-tag',
    '--title',
    tag,
    '--notes-file',
    notesFile,
    ...assets.keys,
  ]);
  if (creation.exitCode != 0) {
    throw PublishException(
      'gh release create $tag failed: ${errorText(creation)}',
    );
  }
  await requireTag('after publishing');
  final created = await releasesOfTag(gh, tag);
  if (created.length != 1) {
    throw PublishException(
      'created $tag, but GitHub lists ${created.length} releases of it',
    );
  }
  final published = {
    for (final asset in (await readRelease(gh, created.single.id)).assets)
      asset.name: asset.digest,
  };
  final problems = [
    for (final MapEntry(key: path, value: sha256) in assets.entries)
      if (published[p.basename(path)] != 'sha256:$sha256')
        '${p.basename(path)}: GitHub reports ${published[p.basename(path)]}, '
            'the local file is sha256:$sha256',
  ];
  if (published.length != assets.length) {
    problems.add(
      'GitHub lists ${published.length} assets; '
      '${assets.length} were uploaded',
    );
  }
  if (problems.isNotEmpty) {
    throw PublishException(
      [
        'created the draft $tag, but its assets are not the packed files:',
        ...problems,
      ].join('\n  '),
    );
  }
}

/// The release notes of the macOS build: the runtime, every pinned grammar
/// and the sha256 of each attached file, from `build_info.json` [info] and
/// [archiveSha256].
///
/// Throws a [PublishException] when [info] records no platform, or one
/// that is not the macOS build a release is created from.
String releaseNotes(Map<String, Object?> info, String archiveSha256) {
  final treeSitter = info['treeSitter']! as Map<String, Object?>;
  final sources = info['sources']! as Map<String, Object?>;
  final generated = info['generated'] as Map<String, Object?>? ?? const {};
  final rows = [
    for (final MapEntry(key: name, value: record) in sources.entries)
      if (record case final Map<String, Object?> record)
        '| $name | `${record['commit']}` | '
            '`${p.basename('${record['file']}')}` | `${record['sha256']}` |',
    for (final MapEntry(key: name, value: record) in generated.entries)
      if (record case final Map<String, Object?> record)
        '| $name, generated by tree-sitter ${record['cli']} | '
            '`${record['commit']}` | `${p.basename('${record['file']}')}` | '
            '`${record['sha256']}` |',
  ];
  final platform = requirePlatform(info['platform']);
  if (!platform.isMacos) {
    throw PublishException(
      'a release is created from the macOS build; build_info.json records '
      'the platform ${platform.id}',
    );
  }
  final runsOn = 'macOS ${info['deploymentTarget']} and later on arm64';
  return 'tree-sitter ${treeSitter['tag']} (${treeSitter['commit']}), '
      '$runsOn.\n\n'
      '`${platform.releaseArchiveName}`: sha256 `$archiveSha256`.\n\n'
      'Every repository the release compiles from, at the commit it pins, '
      'is attached as the source bundle named below, and so are the '
      'sources the pinned CLI generates for a grammar that commits none; '
      'the README says how to rebuild the release from them.\n\n'
      '| Repository | Commit | Source bundle | sha256 |\n'
      '| --- | --- | --- | --- |\n'
      '${rows.join('\n')}\n';
}

/// The release notes [platform]'s release build writes, or null when it
/// writes none.
///
/// Only the macOS build writes notes, since only its release is created
/// from them (`--publish`); a Linux or Windows build packs its archive and
/// stops, and its `build_info.json` is not one [releaseNotes] accepts.
String? releaseNotesOf(
  BuildPlatform platform,
  Map<String, Object?> info,
  String archiveSha256,
) => platform.isMacos ? releaseNotes(info, archiveSha256) : null;
